"""Generate the bundled Area 52 IDs from SELECT entry,type,type_flags ORDER BY entry."""
import sys
from pathlib import Path

def generate(rows):
    known = set()
    eligible = []
    for line in rows:
        entry, kind, flags = map(int, line.split())
        if not 0 < entry <= 0xffffffff or entry in known or not 0 <= kind <= 13:
            raise ValueError('Unexpected creature catalog row')
        known.add(entry)
        if kind and kind != 8:
            eligible.append(entry)
    if not {22313, 15648, 15271, 15294, 15635}.issubset(eligible) or 1 in eligible:
        raise ValueError('Expected the Area 52 catalog with the reviewed starting-area creatures')
    ids = sorted(eligible)
    lines = [', '.join(map(str, ids[i:i + 12])) for i in range(0, len(ids), 12)]
    return ('"""Area 52 non-Critter IDs generated by tools/generate_creature_catalog.py."""\n'
            'NON_CRITTERS = frozenset((\n' + ''.join('    ' + line + ',\n' for line in lines) + '))\n')

if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    output.write_text(generate(source.read_text(encoding='utf-8-sig').splitlines()), encoding='ascii')
